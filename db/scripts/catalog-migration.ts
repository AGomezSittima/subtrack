import { writeFileSync } from "node:fs";
import { join, relative } from "node:path";

import {
  type CatalogEntry,
  checkCatalog,
  installedBuiltins,
  loadCatalog,
  migratedDatabase,
  migrations,
  migrationsDir,
  storedPlans,
} from "./catalog.ts";

const NOW = "strftime('%Y-%m-%dT%H:%M:%fZ', 'now')";

function literal(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function insert(service: CatalogEntry): string {
  const values = [
    literal(service.key),
    literal(service.name),
    literal(service.domain),
    literal(service.category),
  ].join(", ");
  return [
    "INSERT INTO catalog_service (builtin_key, name, domain, category, default_plans, created_at, updated_at) VALUES (",
    `    ${values},`,
    `    ${literal(JSON.stringify(storedPlans(service.plans)))},`,
    `    ${NOW}, ${NOW}`,
    ") ON CONFLICT (builtin_key) DO NOTHING;",
  ].join("\n");
}

const { services, problems } = loadCatalog();
if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const installed = installedBuiltins(migratedDatabase());
const added = services.filter((service) => !installed.has(service.key));
if (added.length === 0) {
  console.log("Every built-in in catalog.json is already in a migration.");
  process.exit(0);
}

const version = (migrations().at(-1)?.version ?? 0) + 1;
const file = join(migrationsDir, `V${String(version)}__catalog_builtins.sql`);
const header =
  "-- Generated by `just catalog-migration` from db/catalog/catalog.json. Flyway checksums applied migrations: never edit this file.";
writeFileSync(file, [header, ...added.map(insert)].join("\n\n") + "\n");
console.log(
  `Wrote ${relative(process.cwd(), file)} with ${String(added.length)} built-in services.`,
);

const remaining = checkCatalog();
if (remaining.length > 0) {
  console.error(remaining.join("\n"));
  process.exit(1);
}
